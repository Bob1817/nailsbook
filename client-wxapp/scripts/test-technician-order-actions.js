const assert = require('assert');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const js = fs.readFileSync(path.join(root, 'pages/technician/order-detail/index.js'), 'utf8');
const wxml = fs.readFileSync(path.join(root, 'pages/technician/order-detail/index.wxml'), 'utf8');
const wxss = fs.readFileSync(path.join(root, 'pages/technician/order-detail/index.wxss'), 'utf8');
const cardJs = fs.readFileSync(path.join(root, 'components/technician-booking-card/index.js'), 'utf8');
const cardWxml = fs.readFileSync(path.join(root, 'components/technician-booking-card/index.wxml'), 'utf8');
const ordersJs = fs.readFileSync(path.join(root, 'pages/technician/orders/index.js'), 'utf8');
const ordersWxml = fs.readFileSync(path.join(root, 'pages/technician/orders/index.wxml'), 'utf8');
const sharedActionsJs = fs.readFileSync(path.join(root, 'pages/technician/utils/technician-booking-actions.js'), 'utf8');
const apiJs = fs.readFileSync(path.join(root, 'services/api.js'), 'utf8');

assert.match(js, /case 'pending_agree':\s+return \[EDIT_QUOTE, WITHDRAW_QUOTE\]/, '待客户确认时必须显示编辑报价和取消报价');
assert.match(js, /case 'pending_shop':\s+return \[EDIT_BOOKING, CANCEL\]/, '客户确认后必须显示编辑预约和取消预约');
const bottomActions = wxml.split('<!-- ============ 底部操作栏 ============ -->')[1].split('</view>\n</view>')[0];
assert(!bottomActions.includes('bindtap="openCancel"'), '底部不得额外硬编码取消预约');
assert.match(wxml, /order\._actions\.length === 2/, '两个操作必须并列展示');
assert.match(wxss, /\.action-secondary\s*\{[^}]*background:\s*var\(--nb-soft-surface\)[^}]*color:\s*var\(--nb-ink\)/, '编辑预约次按钮必须显示完整背景和文字颜色');
assert.match(wxml, /更多操作/, '三个及以上操作必须收起到更多操作');
assert.match(wxml, /wx:for="{{order\._actions}}"/, '更多操作弹层必须展示全部可用操作');
assert.match(wxml, /deposit-summary-amount[^]*定金 ¥/, '最终报价下方必须展示定金金额');
assert.match(wxml, /order\.depositPaid \? '已支付' : '未支付'/, '最终报价下方必须展示独立定金支付状态');
assert.match(wxml, /bindchange="onQuoteDepositStatusChange"/, '发送报价必须用选择器编辑定金支付状态');
assert.match(wxml, /bindchange="onEditDepositStatusChange"/, '调整报价必须用选择器编辑定金支付状态');
assert(!wxml.includes('bindchange="onQuoteDepositPaidChange"'), '发送报价不得继续使用定金支付开关');
assert.match(wxml, /最终报价（元）[^]*deposit-editor[^]*备注（选填）/, '定金编辑必须位于最终报价下方、备注上方');
assert.match(wxml, /quote-sheet-footer[^]*报价明细[^]*原价[^]*最终价格[^]*定金[^]*depositStatusOptions\[quoteDepositStatusIndex\][^]*确认方案/, '固定操作区必须实时展示报价、原价、最终价格、定金及支付状态');
assert.match(wxml, /quote-fixed-summary[^]*quoteSubtotalFen[^]*quoteCorePrice[^]*quoteExtraFen[^]*quoteFinalFen[^]*quoteDepositAmount/, '固定报价信息必须直接绑定当前报价和定金数据');
assert.match(wxml, /class="form-textarea quote-remark-textarea"/, '报价备注必须使用紧凑输入框');
assert.match(wxss, /\.quote-remark-textarea\s*\{[^}]*height:\s*104rpx/, '报价备注输入框高度必须适当压缩');
assert.match(js, /raw\.isDepositPaid[\s\S]*depositAmount > 0[\s\S]*'定金已支付'/, '已支付开关为真且金额为零时仍必须回显定金已支付');
assert.match(js, /depositAmount > 0 \? `待支付定金/, '未支付但已设置金额时必须展示待支付状态和金额');
assert.match(js, /quoteDepositPaid && depositAmount <= 0/, '发送报价时，已支付定金必须填写大于 0 的金额');
assert.match(js, /editDepositPaid && depositFen <= 0/, '更新作品标准报价时，已支付定金必须填写大于 0 的金额');
assert.match(js, /payload\.depositAmount = depositAmount/, '人工覆盖定金时必须按元提交，不能再次乘以100');
assert.match(js, /depositAmount: Number\(depositStr \|\| 0\)/, '调整报价必须按元提交定金');
assert(!js.includes('depositAmount: depositFen'), '不得把以分计算的临时值提交到元字段');
assert.match(wxml, /source-work-title[\s\S]*sourceWork\._priceFen \/ 100/, '预约来源作品标题下方必须展示统一口径的作品价格');
assert.match(js, /raw\.sourceWorkId[\s\S]*api\.technician\.works\.detail\(sourceWorkId\)/, '线上详情仅返回作品 ID 时必须补拉作品详情');
assert.match(apiJs, /withdrawQuote: \(id\) => api\.patch\(`\$\{T\}\/orders\/\$\{id\}\/withdraw-quote`/, '小程序 API 必须提供撤回报价动作');
assert.match(cardWxml, /order\._actionStatus === 'pending_agree'[^]*取消报价[^]*编辑报价/, '行程卡片待客户确认时必须显示取消报价和编辑报价');
assert.match(cardWxml, /order\._actionStatus === 'pending_confirm'[^]*驳回申请[^]*同意预约/, '行程卡片待我确认时必须显示驳回申请和同意预约');
assert.match(cardWxml, /order\._actionStatus === 'pending_shop'[^]*编辑预约[^]*取消预约/, '行程卡片待到店时必须显示编辑预约和取消预约');
assert.match(cardJs, /variant === 'confirmation'[\s\S]*setData\(\{ confirming: this\.data\.order \}\)/, '列表卡片待我确认时必须内置打开确认排期弹层');
assert.match(cardWxml, /booking-confirm[^]*bind:saved="onConfirmDialogSaved"/, '确认排期弹层必须接入行程卡片');
assert.match(cardJs, /triggerEvent\('confirmed'/, '确认成功后必须通知页面刷新');
assert.match(sharedActionsJs, /onBookingCardConfirmed: \(page\) => reload\(page\)/, '共享预约操作必须提供确认成功后的刷新处理');
assert.match(ordersWxml, /bind:confirmed="onBookingCardConfirmed"/, '行程页必须监听确认成功事件');
const confirmJs = fs.readFileSync(path.join(root, 'components/booking-confirm/index.js'), 'utf8');
const confirmWxml = fs.readFileSync(path.join(root, 'components/booking-confirm/index.wxml'), 'utf8');
assert.match(confirmWxml, /mode="date"[\s\S]*mode="time"/, '确认弹层必须支持编辑预约日期与时间');
assert.match(confirmJs, /orders\.quote\(order\.id, \{[\s\S]*useCurrentServices: true[\s\S]*serviceDate: this\.data\.dateValue[\s\S]*startTime: this\.data\.timeValue/, '有报价的改期确认必须整体走方案确认接口由客户重新确认');
assert.match(confirmJs, /orders\.confirm\(order\.id, \{[\s\S]*price: Number\(price\)/, '未改期时确认排期必须直接调用确认接口进入待到店');
assert.match(apiJs, /quote: \(id, data\) => api\.patch\(`\$\{T\}\/orders\/\$\{id\}\/review`/, '小程序 API 必须提供方案确认（报价审核）接口');
assert.match(cardJs, /triggerEvent\('withdrawquote'/, '预约卡片必须向页面派发撤回报价事件');
assert.match(ordersWxml, /bind:withdrawquote="onBookingCardWithdrawQuote"/, '行程页必须监听撤回报价事件');
assert.match(ordersJs, /technicianBookingCardHandlers/, '行程页必须接入共享预约操作');
assert.match(sharedActionsJs, /api\.technician\.orders\.withdrawQuote\(id\)/, '共享预约操作必须调用撤回报价接口');

const normalizeWork = fs.readFileSync(path.join(root, 'utils/normalize-work.js'), 'utf8');
assert.match(normalizeWork, /standardPriceFen \|\| raw\.serviceSubtotalFen \|\| raw\.priceCents/, '预约详情作品价格必须复用作品卡片的多字段价格口径');

console.log('美甲师预约详情操作布局检查通过');

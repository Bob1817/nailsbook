const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const file = path.resolve(__dirname, '../pages/technician/customers/index.js');
const context = { require: () => ({}), Page() {}, Date };
vm.runInNewContext(fs.readFileSync(file, 'utf8'), context);
const decorate = context.decorateCustomer;
const label = context.formatDateLabel;
const today = new Date(2026, 8, 6, 0, 10);
assert.equal(label(new Date(2026, 8, 5, 23, 50), today), '昨天', '跨午夜按日历日期计算');
assert.equal(label(new Date(2026, 8, 6, 20), today), '今天');
assert.equal(label('2026-09-07', today), '明天');
assert.equal(label('2026-09-20', today), '9月20日', '未来复购日期不能标成今天');
assert.equal(label('2026-09-04', today), '2天前');
assert.equal(label('2025-09-06', today), '2025年9月6日');
assert.equal(label('2027-01-05', today), '2027年1月5日');
assert.equal(label('2027-01-01', new Date(2026, 11, 31, 12)), '明天');
assert.equal(label('not-a-date', today), '');
assert.equal(label('2026-02-30', today), '');
assert.equal(label('', today), '');
const active = { lifecycle: { status: 'active', expectedNextServiceAt: '2026-09-01' } };
assert.equal(decorate(active)._lifecycleLabel, '活跃');
assert.equal(decorate({ ...active, bindingStatus: 'inactive' })._lifecycleLabel, '已解绑');
assert.equal(decorate({ ...active, bindingStatus: 'inactive' })._expectedServiceText, '');
assert.equal(decorate({ ...active, bindingStatus: 'inactive', account: { status: 'deleted' } })._lifecycleLabel, '已注销');
assert.equal(decorate({ ...active, account: { linked: false } })._lifecycleLabel, '活跃');
assert.equal(decorate({ ...active, anonymizedAt: '2026-08-28' })._lifecycleLabel, '活跃');
for (const status of ['new', 'due', 'dormant']) assert.equal(decorate({ lifecycle: { status } })._lifecycleClass, 'lifecycle-' + status);
const css = fs.readFileSync(file.replace('.js', '.wxss'), 'utf8');
assert(css.includes('.lifecycle-active { background: var(--nb-success-surface); color: var(--nb-success); }'));
assert(css.includes('text-align: center;'));
assert(!css.includes('.stat-item:first-child'));
console.log('Customer lifecycle, account precedence and centered metrics checks passed.');

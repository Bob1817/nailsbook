const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { createRequire } = require('node:module');
const file = path.join(__dirname, '../pages/client/create-order/index.js');
let definition;
vm.runInNewContext(fs.readFileSync(file, 'utf8'), {
  Page: value => { definition = value; }, require: name => name.includes('services/api') ? { public: {} } : createRequire(file)(name), console
});
const page = { ...definition, data: { ...definition.data },
  setData(value) { Object.assign(this.data, value); }, loadTechWorks() {} };
function choose(shops) {
  page.data.technicians = [{ id: 7, shopService: true, shopAddresses: shops, serviceItems: [] }];
  page.selectTech({ currentTarget: { dataset: { id: 7 } } });
}
choose([{ name: '唯一店' }, { name: '停用店', enabled: false }]);
assert.equal(page.data.selectedShopName, '唯一店');
assert.equal(page.data.serviceType, '到店美甲');
assert.equal(page.data.selectedServiceOptionKey, 'shop:0:唯一店');
choose([{ name: '唯一店' }]);
page.data.startTime = '10:00';
page.selectServiceType({ currentTarget: { dataset: { value: '到店美甲' } } });
assert.equal(page.data.startTime, '10:00', '重复点击已选类型不清空预约时间');
page.selectServiceType({ currentTarget: { dataset: { value: '未开放服务' } } });
assert.equal(page.data.serviceType, '到店美甲', '不能选中未开放类型');
page._bookingDraft = { selectedTechId: 7, selectedShopName: '' };
page.restoreDraft();
assert.equal(page.data.selectedShopName, '唯一店', '空草稿不覆盖唯一门店');
choose([{ name: '甲店' }, { name: '乙店' }]);
assert.equal(page.data.selectedShopName, '', '多店不擅自选中');
assert.equal(page.data.serviceType, '', '多种服务形式必须由客户单选');
page._draftRestored = false;
page._bookingDraft = { selectedTechId: 7, selectedShopName: '乙店' };
page.restoreDraft();
assert.equal(page.data.selectedShopName, '乙店', '保留有效草稿门店');
page._draftRestored = false;
page._bookingDraft.selectedShopName = '已删除店';
page.restoreDraft();
assert.equal(page.data.selectedShopName, '', '不恢复失效门店');
choose([]);
assert.equal(page.data.selectedShopName, '');
page.data.activeServiceItems = [{ id: 1, price: 198, durationMinutes: 60 }, { id: 2, price: 498, durationMinutes: 120 }];
page.toggleService({ currentTarget: { dataset: { id: 1 } } });
assert.equal(page.data.selectedServiceMap[1], true, '选中服务显示勾选');
assert.equal(page.data.selectedServiceTotal, 198);
page.toggleService({ currentTarget: { dataset: { id: 2 } } });
assert.equal(page.data.selectedServiceMap[2], true);
assert.equal(page.data.selectedServiceTotal, 696);
page.toggleService({ currentTarget: { dataset: { id: 1 } } });
assert.equal(page.data.selectedServiceMap[1], undefined, '取消服务清除勾选');
assert.equal(page.data.selectedServiceTotal, 498);
choose([{ name: '新门店' }]);
assert.equal(Object.keys(page.data.selectedServiceMap).length, 0, '切换美甲师清除旧选择');
page._draftRestored = false;
page._bookingDraft = { selectedTechId: 7, selectedServiceIds: [2] };
page.restoreDraft();
assert.equal(page.data.selectedServiceMap[2], true, '草稿恢复勾选状态');
const template = fs.readFileSync(path.join(__dirname, '../pages/client/create-order/index.wxml'), 'utf8');
const css = fs.readFileSync(path.join(__dirname, '../pages/client/create-order/index.wxss'), 'utf8');
assert(!template.includes('selectedServiceIds.indexOf('), 'WXML禁止调用数组方法判断服务选中');
assert(template.includes('selectedServiceMap[item.id]'));
assert(!template.includes('<text class=\"type-duration\">约 {{item.durationMinutes}} 分钟</text>'), '服务卡片仅展示名称与价格，时长保留在无障碍说明和排班计算中');
assert(/\.service-list\s*\{[^}]*grid-template-columns:\s*repeat\(2/.test(css), '服务选择使用双列卡片');
assert(/\.service-card-active\s*\{[^}]*background:\s*var\(--nb-action\);[^}]*color:\s*var\(--nb-inverse\)/.test(css), '选中服务使用黑底白字');
assert(template.includes('<radio-group') && template.includes('bindchange="selectServiceOption"') && template.includes('<radio class="service-option-native"'), '服务形式使用原生单选组');
assert(template.includes('service-option-radio-dot'), '单选项使用圆点而不是勾选图标');
assert.match(css, /\.service-option-radio\s*\{[^}]*width:\s*26rpx;[^}]*height:\s*26rpx;/s, '服务形式单选图标应与正文大小匹配');
assert.match(css, /\.service-option-radio\s*\{[^}]*margin-top:\s*8rpx;/s, '服务形式单选图标应与首行标题垂直居中');
assert.match(css, /\.service-option-radio-dot\s*\{[^}]*width:\s*10rpx;[^}]*height:\s*10rpx;/s, '服务形式选中圆点不应过大');
assert.match(css, /\.addr-card-active\s*\{[^}]*background:\s*var\(--nb-active-surface\);/s, '服务形式选中状态应提供背景反馈');
assert.doesNotMatch(css, /\.addr-card-active\s*\{[^}]*border(?:-color)?:/s, '服务形式选中状态不应显示卡片描边');
assert(template.includes('{{item.title}}') && template.includes('{{item.detail}}'), '每个服务形式同时展示类型和对应地址');
page.data.technicians = [{ id: 8, shopService: true, homeService: true, shopAddresses: [{ name: '门店 A' }], serviceItems: [] }];
page.selectTech({ currentTarget: { dataset: { id: 8 } } });
assert.equal(page.data.serviceOptions.length, 1, '首发版忽略后端遗留的上门服务标记');
assert.equal(page.data.serviceType, '到店美甲');
assert.equal(page.data.selectedShopName, '门店 A');
assert(/\.addr-guidance-link\s*\{[^}]*min-height: 88rpx;[^}]*margin: -16rpx 0 -16rpx;/.test(css));
console.log('首发到店门店、草稿恢复和选择标记检查通过');

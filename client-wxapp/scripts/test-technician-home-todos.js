const assert = require('assert');
const fs = require('fs');
const path = require('path');

const root = path.join(__dirname, '..');
const read = (file) => fs.readFileSync(path.join(root, file), 'utf8');
const home = read('pages/technician/home/index.js');
const homeWxml = read('pages/technician/home/index.wxml');
const homeWxss = read('pages/technician/home/index.wxss');
const bookingCard = read('components/technician-booking-card/index.wxml');
const bookingCardJs = read('components/technician-booking-card/index.js');
const bookingCardWxss = read('components/technician-booking-card/index.wxss');
const orders = read('pages/technician/orders/index.js');
const tradeOrders = read('pages/technician/trade-orders/index.js');
const allBookings = read('pages/technician/all-bookings/index.js');

assert(home.includes("'/pages/technician/orders/index?task=pending'"), '待处理预约必须进入可处理预约筛选');
assert(home.includes('todo.count === 1 && todo.targetId') && home.includes('/pages/technician/order-detail/index?id='), '单个待支付定金预约必须直达预约详情');
assert(home.includes("'/pages/technician/all-bookings/index?filter=unpaid_deposit'"), '多个待支付定金预约必须进入对应筛选列表');
assert(orders.includes("options.task === 'pending'"), '预约列表必须读取待处理筛选参数');
assert(orders.includes("o.status === 'pending_quote' || o.status === 'pending_confirm'"), '待处理预约必须包含待报价和待我确认');
assert(home.includes("o.status === 'pending_confirm'"), '待我确认必须由预约状态驱动，不能依赖消息未读状态');
assert(home.includes('confirmationTodos'), '首页必须展示待我确认预约的核心信息');
assert(home.includes('openOrderDetail'), '待我确认预约必须可直接进入预约详情');
assert(!homeWxml.includes('今日行程'), '首页必须移除无用途的今日行程卡片');
assert(homeWxml.includes('variant="confirmation"'), '待确认事项必须复用预约卡片组件');
assert(bookingCard.includes('{{order._clock}}') && bookingCard.includes('{{order._priceText}}'), '待确认预约卡片必须突出时间和价格');
assert(home.includes('confirmationSummary(order)'), '二次确认弹窗必须提供明确预约摘要');
assert(homeWxml.includes('<booking-confirm') && home.includes('confirmationOrder: order'), '确认排期必须使用独立表单展示完整内容');
assert(bookingCard.includes("{{order.customerName || '客户'}}") && bookingCard.includes('order._shopName'), '待确认预约卡片必须展示客户与地址信息');
assert(bookingCard.includes('order.serviceName'), '待确认事项应保持预约卡片的服务信息层级');
assert(homeWxml.includes('bind:refuse="refuseConfirmation"') && homeWxml.includes('bind:confirm="confirmConfirmation"') && bookingCard.includes('查看详情'), '待确认卡片必须提供拒绝、确认和详情操作');
assert(bookingCardJs.includes("triggerEvent('refuse'") && bookingCardJs.includes("triggerEvent('confirm'"), '预约卡片必须向页面传递待办操作');
assert(bookingCardWxss.includes('grid-template-columns:repeat(3,minmax(0,1fr))') && bookingCardWxss.includes('height:44px'), '三个操作应使用等宽且触控友好的统一按钮');
assert(bookingCardWxss.includes('confirmation-button-secondary') && bookingCardWxss.includes('confirmation-button-primary') && bookingCardWxss.includes('confirmation-button-tertiary'), '拒绝、确认和详情必须使用统一按钮层级');
assert(/\.confirmation-button-secondary\s*\{[^}]*color:var\(--nb-danger\)/.test(bookingCardWxss), '拒绝排期必须使用红色警示文字');
assert(home.includes("label: '个预约待支付定金'"), '定金待办必须使用预约工作流口径');
assert(tradeOrders.includes("options.filter === 'pending'"), '交易订单必须读取待支付筛选参数');
assert(home.includes('Number(o.depositAmount || 0) > 0') && home.includes('unpaidDepositOrders[0].id'), '定金待办只能统计有定金金额的预约，并保留单条预约 ID');
assert(allBookings.includes("options.filter === 'unpaid_deposit'") && allBookings.includes("value === 'unpaid_deposit'"), '全部预约页必须支持待支付定金筛选');
assert(/\.todo-left\s*\{[^}]*gap:\s*8rpx/.test(homeWxss), '待办数量与文案应保持紧凑间距');

console.log('美甲师首页待处理事项导航检查通过');
